/* KT: 翻訳取得。ja をフォールバックにし、キー欠落時はキー名を返して事故を可視化する。
   {name} 形式のプレースホルダを vars で差し替える。 */
window.KT = function(key, vars){
  var dict = window.KB_I18N[window.KB_LANG] || window.KB_I18N.ja;
  var s = dict[key];
  if(s === undefined) s = window.KB_I18N.ja[key];
  if(s === undefined) return key;
  if(vars) s = String(s).replace(/\{(\w+)\}/g, function(m, k){
    return vars[k] !== undefined ? String(vars[k]) : m;
  });
  return s;
};
/* 静的マークアップ側の差し替え。textContent / placeholder / title / aria-label に対応。 */
window.applyI18N = function(root){
  var scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(function(el){
    el.textContent = window.KT(el.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-ph]').forEach(function(el){
    el.setAttribute('placeholder', window.KT(el.getAttribute('data-i18n-ph')));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach(function(el){
    var v = window.KT(el.getAttribute('data-i18n-title'));
    el.setAttribute('title', v); el.setAttribute('aria-label', v);
  });
  scope.querySelectorAll('[data-i18n-aria]').forEach(function(el){
    el.setAttribute('aria-label', window.KT(el.getAttribute('data-i18n-aria')));
  });
};
